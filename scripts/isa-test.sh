#!/usr/bin/env bash
# scripts/isa-test.sh -- ISA-level validation: generate, build, run on silicon and the
# emulator, compare, analyze.
#
# tools/isa-test-gen.py writes a harness suite (one case per batch of single-instruction
# tests; the cascade and stream batches are two-core cases) and the suite runner
# (tools/harness/suite.py) owns everything else: assembling, packaging with aiecc
# (unchanged cases are reused by content hash), serial hardware runs, parallel EMU runs,
# the byte-exact compare.  tools/isa-test-analyze.py then reports per test point.
#
# This tests raw ISA instruction behavior (assembly level); the intrinsic-level (C++)
# suites are generated by tools/instr-test-gen.py and tools/chess-test-gen.py and run with
# the same suite runner (docs/components/testing.md).
#
# Usage:
#   scripts/isa-test.sh [options]
#
# Options:
#   --seed N         PRNG seed of the input data (default: 42)
#   -j N             Parallelism for packaging + EMU (default: nproc)
#   --generate-only  Only run the generator, skip build/run
#   --filter PAT     Only run cases matching PAT (grep -E on case name, source type
#                    or instruction name; e.g. 'cascade_pair', 'VMOV')
#   --tag NAME       Run id (default: timestamp); runs are tagged hw-NAME / emu-NAME
#                    and never overwritten
#   --with-amdxdna-trace   ringbuffer-capture amdxdna kernel tracepoints around the
#                    HW phase (needs sudo; opt in when debugging mid-suite wedges)
#
# Everything lives in build/isa-suite (override: ISA_SUITE_DIR); the file `last` there
# names the newest run id, which tools/isa-test-analyze.py SUITE_DIR uses by default.
# XDNA_EMU_RUNTIME=release|debug picks the EMU profile (default debug).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
ISA_JSON="${PROJECT_DIR}/tools/aie2-isa.json"
SUITE_DIR="${ISA_SUITE_DIR:-${PROJECT_DIR}/build/isa-suite}"
export PYTHONPATH="${PROJECT_DIR}/tools${PYTHONPATH:+:$PYTHONPATH}"

SEED=42
JOBS=$(nproc)
GENERATE_ONLY=false
FILTER=""
RUN_ID="$(date +%Y%m%d-%H%M%S)"
AMDXDNA_TRACE=false

while [[ $# -gt 0 ]]; do
    case "$1" in
        --seed)             SEED="$2"; shift 2 ;;
        -j)                 JOBS="$2"; shift 2 ;;
        --generate-only)    GENERATE_ONLY=true; shift ;;
        --filter)           FILTER="$2"; shift 2 ;;
        --tag)              RUN_ID="$2"; shift 2 ;;
        --with-amdxdna-trace) AMDXDNA_TRACE=true; shift ;;
        *)                  echo "Unknown option: $1"; exit 1 ;;
    esac
done

HW_TAG="hw-${RUN_ID}"
EMU_TAG="emu-${RUN_ID}"
harness() { python3 -m harness suite "$@"; }

echo "=== ISA-Level Validation Harness ==="
echo "Suite:    $SUITE_DIR"
echo "Run:      $RUN_ID (seed $SEED)"
echo ""

# ---- Phase 1: Generate ----
echo "--- Phase 1: Generate ---"
python3 "${PROJECT_DIR}/tools/isa-test-gen.py" \
    --isa-json "$ISA_JSON" --suite-dir "$SUITE_DIR" --seed "$SEED"
echo ""

if $GENERATE_ONLY; then
    echo "Generate-only mode. Done."
    exit 0
fi

ONLY=()
if [[ -n "$FILTER" ]]; then
    mapfile -t ONLY < <(python3 -c "
import sys
import isa_suite
from harness import suite
for c in isa_suite.filter_cases(suite.load_suite(sys.argv[1]), sys.argv[2]):
    print(c)" "$SUITE_DIR" "$FILTER")
    if [[ ${#ONLY[@]} -eq 0 ]]; then
        echo "No cases match filter. Done."
        exit 0
    fi
fi
SELECT=()
[[ ${#ONLY[@]} -gt 0 ]] && SELECT=(--only "${ONLY[@]}")
if [[ ${#ONLY[@]} -gt 0 ]]; then echo "Cases to run: ${#ONLY[@]}"; else echo "Cases to run: all"; fi
echo ""

# ---- Phase 2: Assemble + package ----
echo "--- Phase 2: Assemble + package (unchanged cases are reused) ---"
harness build "$SUITE_DIR" "${SELECT[@]}" -j "$JOBS"
echo ""

# ---- Phase 3: Run HW (serial) ----
# Capture amdxdna kernel tracepoints (xdna_job, mailbox, IRQ, fence) for the duration
# of the HW phase.  Single-sudo daemon design: the daemon holds tracing on for the whole
# phase under one auth and snapshots+disables when the sentinel is removed.  Its EXIT
# trap also handles parent-died and signal-killed cases.
AMDXDNA_SENTINEL=""
AMDXDNA_DAEMON_PID=""
if $AMDXDNA_TRACE; then
    TRACE_DIR="${SUITE_DIR}/runs/trace-${RUN_ID}"
    mkdir -p "$TRACE_DIR"
    AMDXDNA_SENTINEL=$(mktemp /tmp/claude-1000/amdxdna-trace.isa.XXXXXX 2>/dev/null \
                       || mktemp /tmp/amdxdna-trace.isa.XXXXXX)
    # stdin from /dev/null: the backgrounded sudo must never compete with the
    # foreground script for the terminal.  With no agent and no tty, sudo exits
    # non-zero at once rather than hanging, which the liveness check reports.
    sudo "$PROJECT_DIR/tools/amdxdna-trace.sh" daemon \
        "$AMDXDNA_SENTINEL" $$ "$TRACE_DIR" amdxdna </dev/null &
    AMDXDNA_DAEMON_PID=$!
    sleep 1   # let daemon set up tracing before HW jobs start
    if ! kill -0 $AMDXDNA_DAEMON_PID 2>/dev/null; then
        daemon_rc=0
        wait $AMDXDNA_DAEMON_PID || daemon_rc=$?
        echo "WARN: amdxdna-trace daemon failed to start (sudo/daemon exit $daemon_rc); continuing without it"
        AMDXDNA_TRACE=false
        rm -f "$AMDXDNA_SENTINEL"
    fi
fi

echo "--- Phase 3: Run HW (serial) ---"
hw_rc=0
harness hw "$SUITE_DIR" "$HW_TAG" "${SELECT[@]}" || hw_rc=$?
echo ""

if $AMDXDNA_TRACE; then
    rm -f "$AMDXDNA_SENTINEL"
    wait "$AMDXDNA_DAEMON_PID" 2>/dev/null || true
fi
if [[ $hw_rc -ne 0 ]]; then
    echo "FATAL: Hardware run failed or timed out (see ${SUITE_DIR}/runs/${HW_TAG}). Aborting."
    exit 1
fi

# ---- Phase 4: Run EMU (parallel; rebuilds the FFI .so first) ----
echo "--- Phase 4: Run EMU (j=$JOBS) ---"
if ! harness emu "$SUITE_DIR" "$EMU_TAG" "${SELECT[@]}" -j "$JOBS"; then
    echo "FATAL: Emulator run failed (see ${SUITE_DIR}/runs/${EMU_TAG}). Aborting."
    exit 1
fi
echo ""
echo "$RUN_ID" > "${SUITE_DIR}/last"

# ---- Phase 5: Compare ----
echo "--- Phase 5: Compare ---"
status=0
harness compare "$SUITE_DIR" "$HW_TAG" "$EMU_TAG" "${SELECT[@]}" || status=1
echo ""

# ---- Phase 6: Test-point analysis ----
ANALYZER="${PROJECT_DIR}/tools/isa-test-analyze.py"
ANALYSIS_LOG="${SUITE_DIR}/runs/${EMU_TAG}/analysis.log"
DETAIL_LOG="${SUITE_DIR}/runs/${EMU_TAG}/analysis-failing.log"
echo "--- Phase 6: Test-Point Analysis ---"
# A failed test point (EMU != HW, or a hollow test that checked nothing) fails the run.
python3 "$ANALYZER" "$SUITE_DIR" "$HW_TAG" "$EMU_TAG" --summary 2>&1 | tee "$ANALYSIS_LOG"
[[ ${PIPESTATUS[0]} -eq 0 ]] || status=1
python3 "$ANALYZER" "$SUITE_DIR" "$HW_TAG" "$EMU_TAG" --failing > "$DETAIL_LOG" 2>&1
echo ""
echo "Analysis logs written to:"
echo "  Summary:  $ANALYSIS_LOG"
echo "  Detailed: $DETAIL_LOG"
exit $status
