/// Render the perishable queue (spec Section 1) as deterministic markdown:
/// one row per op with its perishable variants, grouped by provenance. This
/// is the semantic half of the derivation backlog, so it names every op and,
/// where only some variants are perishable, which ones.
pub fn render_perishable(arch: Architecture) -> String {
    let m = CoverageModel::build(arch);
    let mut lines = vec![
        format!("# Perishable queue ({arch})"),
        String::new(),
        "Generated by `cargo run -p xdna-archspec --example gen_coverage_artifacts`. Do not hand-edit."
            .to_string(),
        String::new(),
        "Modeled, weak provenance, silicon-unverified (spec Section 1). Empty == this".to_string(),
        "axis of the per-silicon release gate is green for this arch. Coverage is per".to_string(),
        "(op, variant) (`coverage/variant.rs`); a variant leaves the queue when a".to_string(),
        "silicon capture verifies it (an override unit in `coverage/units.rs`). The".to_string(),
        "full ledger is semantic-ops.md.".to_string(),
        String::new(),
    ];
    let ledger = m.semantic_ledger();
    if !ledger.iter().any(|r| r.verdict.is_perishable()) {
        lines.push("_empty_".to_string());
    }
    for prov in [Provenance::ModelInformed, Provenance::DocSpecified] {
        let rows = op_rows(&ledger, |r| r.verdict.is_perishable() && r.verdict.provenance == prov);
        if rows.is_empty() {
            continue;
        }
        let n: usize = rows.iter().map(|r| r.hit.len()).sum();
        lines.push(format!("## {}, unverified ({} ops, {n} variants)", provenance_label(&prov), rows.len()));
        lines.push(String::new());
        lines.extend(rows.iter().map(OpRow::line));
        lines.push(String::new());
    }
    format!("{}\n", lines.join("\n").trim_end_matches('\n'))
}

/// One op's share of a filtered ledger view: the matching variants out of all.
struct OpRow {
    op: crate::aie2::isa::SemanticOp,
    category: Category,
    hit: Vec<String>,
    total: usize,
}

impl OpRow {
    /// `- \`Op\` (Category): k of n variants[: v1, v2, ...]`; the list is
    /// omitted when every variant matches.
    fn line(&self) -> String {
        let head =
            format!("- `{:?}` ({:?}): {} of {} variants", self.op, self.category, self.hit.len(), self.total);
        if self.hit.len() == self.total {
            head
        } else {
            format!("{head}: {}", self.hit.join(", "))
        }
    }
}

/// Group the ledger rows matching `keep` by op, in ledger order.
fn op_rows(ledger: &[SemanticLedgerRow], keep: impl Fn(&SemanticLedgerRow) -> bool) -> Vec<OpRow> {
    let mut rows: Vec<OpRow> = Vec::new();
    for r in ledger {
        if rows.last().map(|o| o.op) != Some(r.op) {
            rows.push(OpRow { op: r.op, category: r.category, hit: Vec::new(), total: 0 });
        }
        let o = rows.last_mut().unwrap();
        o.total += 1;
        if keep(r) {
            o.hit.push(format!("`{}`", r.variant));
        }
    }
    rows.retain(|o| !o.hit.is_empty());
    rows
}

/// A variant cell: the key, plus the intrinsic family for config modes.
fn variant_cell(v: &OpVariant) -> String {
    match v.mode_family() {
        Some(family) => format!("`{v}` {family}"),
        None => format!("`{v}`"),
    }
}

/// Render every (op, variant) verdict and the evidence behind it: the full
/// ledger the perishable and comprehension queues are views of. An op summary
/// (worst-wins over variants) comes first, then every variant.
pub fn render_semantic_ledger(arch: Architecture) -> String {
    let m = CoverageModel::build(arch);
    let ledger = m.semantic_ledger();
    let mut lines = vec![
        format!("# Semantic op ledger ({arch})"),
        String::new(),
        "Generated by `cargo run -p xdna-archspec --example gen_coverage_artifacts`. Do not hand-edit."
            .to_string(),
        String::new(),
        "Every SemanticOp variant (`coverage/variant.rs`) with its provenance and".to_string(),
        "verification verdict. An op's verdict is the worst over its variants.".to_string(),
        "\"Claimed by\" names the override unit that set the verdict (evidence below);".to_string(),
        "`-` means the category default from `coverage/derive.rs`. Config-mode".to_string(),
        "variants are `mac(amode,bmode,variant,<x sign><y sign>)` (s = signed) or".to_string(),
        "`acc(amode,bmode,variant)`, followed by their `aiev2_vmult.h` family.".to_string(),
        String::new(),
        "## Ops".to_string(),
        String::new(),
        "| Op | Category | Variants | Verified | Provenance | Verification |".to_string(),
        "|----|----------|----------|----------|------------|--------------|".to_string(),
    ];
    for o in op_rows(&ledger, |_| true) {
        let verified = ledger
            .iter()
            .filter(|r| r.op == o.op && matches!(r.verdict.verification, Verification::Verified { .. }))
            .count();
        let v = m.semantic_verdict(&o.op);
        lines.push(format!(
            "| `{:?}` | {:?} | {} | {verified} | {} | {} |",
            o.op,
            o.category,
            o.total,
            provenance_label(&v.provenance),
            verification_label(&v.verification),
        ));
    }
    lines.push(String::new());
    lines.push("## Variants".to_string());
    lines.push(String::new());
    lines.push("| Op | Variant | Provenance | Verification | Claimed by |".to_string());
    lines.push("|----|---------|------------|--------------|------------|".to_string());
    for r in &ledger {
        lines.push(format!(
            "| `{:?}` | {} | {} | {} | {} |",
            r.op,
            variant_cell(&r.variant),
            provenance_label(&r.verdict.provenance),
            verification_label(&r.verdict.verification),
            r.claimed_by.as_deref().unwrap_or("-"),
        ));
    }
    let mut units: Vec<&str> = Vec::new();
    for r in &ledger {
        if let Some(id) = r.claimed_by.as_deref() {
            if !units.contains(&id) {
                units.push(id);
            }
        }
    }
    if !units.is_empty() {
        lines.push(String::new());
        lines.push("## Evidence".to_string());
        for id in units {
            let u = m.unit(id).expect("a claiming unit is registered");
            let text = match &u.verdict.verification {
                Verification::Verified { evidence } => evidence.as_str(),
                Verification::Accepted { rationale } => rationale.as_str(),
                Verification::Contradicted { evidence } => evidence.as_str(),
                _ => u
                    .shadows_derived
                    .as_deref()
                    .unwrap_or("(no evidence text: verdict carries none)"),
            };
            lines.push(String::new());
            lines.push(format!("### {id}"));
            lines.push(String::new());
            lines.push(one_line(text));
        }
    }
    lines.push(String::new());
    format!("{}\n", lines.join("\n").trim_end_matches('\n'))
}

/// Render the timing-constant provenance ledger for `arch`, valued from
/// `timing`: the numeric half of the derivation backlog. Backlog rows (silicon
/// contradicts the value, or nothing verifies it) come first, contradicted
/// before unverified; settled rows carry their evidence.
pub fn render_timing_constants(arch: Architecture, timing: &TimingModel) -> String {
    let values: std::collections::HashMap<String, serde_json::Value> =
        timing_leaves(timing).into_iter().collect();
    let reg = timing_constant_registry(arch);
    let value = |path: &str| values.get(path).map(|v| v.to_string()).unwrap_or_else(|| "?".into());
    let mut lines = vec![
        format!("# Timing constants ({arch})"),
        String::new(),
        "Generated by `cargo run -p xdna-archspec --example gen_coverage_artifacts`. Do not hand-edit."
            .to_string(),
        String::new(),
        "Every `TimingModel` field with its provenance and verification verdict".to_string(),
        "(`coverage/constants.rs`). The backlog lists what silicon contradicts or".to_string(),
        "nothing has verified yet; settled values are toolchain-derived or measured.".to_string(),
        String::new(),
    ];
    let rank = |u: &&ConstantUnit| match u.verdict.verification {
        Verification::Contradicted { .. } => 0,
        _ => 1,
    };
    let mut backlog: Vec<&ConstantUnit> = reg
        .iter()
        .filter(|u| {
            matches!(u.verdict.verification, Verification::Unverified | Verification::Contradicted { .. })
        })
        .collect();
    backlog.sort_by_key(rank);
    let settled: Vec<&ConstantUnit> =
        reg.iter().filter(|u| !backlog.iter().any(|b| b.path == u.path)).collect();
    lines.push(format!("## Backlog ({})", backlog.len()));
    lines.push(String::new());
    lines.push("| Constant | Value | Provenance | Verification | Note |".to_string());
    lines.push("|----------|-------|------------|--------------|------|".to_string());
    for u in &backlog {
        lines.push(format!(
            "| `{}` | {} | {} | {} | {} |",
            u.path,
            value(u.path),
            provenance_label(&u.verdict.provenance),
            verification_label(&u.verdict.verification),
            one_line(u.note),
        ));
    }
    lines.push(String::new());
    lines.push(format!("## Settled ({})", settled.len()));
    lines.push(String::new());
    lines.push("| Constant | Value | Provenance | Verification | Evidence and note |".to_string());
    lines.push("|----------|-------|------------|--------------|-------------------|".to_string());
    for u in &settled {
        let evidence = match &u.verdict.verification {
            Verification::Verified { evidence } => evidence.as_str(),
            _ => "",
        };
        let text = [evidence, u.note]
            .iter()
            .filter(|t| !t.is_empty())
            .cloned()
            .collect::<Vec<_>>()
            .join(" -- ");
        lines.push(format!(
            "| `{}` | {} | {} | {} | {} |",
            u.path,
            value(u.path),
            provenance_label(&u.verdict.provenance),
            verification_label(&u.verdict.verification),
            one_line(&text),
        ));
    }
    let contradicted: Vec<&&ConstantUnit> = backlog.iter().filter(|u| rank(u) == 0).collect();
    if !contradicted.is_empty() {
        lines.push(String::new());
        lines.push("## Contradicting evidence".to_string());
        for u in contradicted {
            if let Verification::Contradicted { evidence } = &u.verdict.verification {
                lines.push(String::new());
                lines.push(format!("### {}", u.path));
                lines.push(String::new());
                lines.push(one_line(evidence));
            }
        }
    }
    lines.push(String::new());
    format!("{}\n", lines.join("\n").trim_end_matches('\n'))
}

/// Collapse source-wrapped text onto one line (markdown table cells).
fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn provenance_label(p: &Provenance) -> &'static str {
    match p {
        Provenance::ToolchainDerived => "toolchain-derived",
        Provenance::ModelInformed => "model-informed",
        Provenance::DocSpecified => "doc-specified",
        Provenance::Unspecified => "unspecified",
        Provenance::HardwareObserved => "hardware-observed",
    }
}

fn verification_label(v: &Verification) -> &'static str {
    match v {
        Verification::NotApplicable => "n/a",
        Verification::Verified { .. } => "silicon-verified",
        Verification::Unverified => "unverified",
        Verification::Contradicted { .. } => "CONTRADICTED",
        Verification::Accepted { .. } => "accepted",
        Verification::Modeled { .. } => "modeled",
    }
}

/// Render the comprehension gaps (spec Section 1) as deterministic markdown.
pub fn render_comprehension(arch: Architecture) -> String {
    let m = CoverageModel::build(arch);
    let n = m.comprehension_gaps().len();
    let mut lines = vec![
        format!("# Comprehension gaps ({arch})"),
        String::new(),
        "Generated by `cargo run -p xdna-archspec --example gen_coverage_artifacts`. Do not hand-edit."
            .to_string(),
        String::new(),
        "A trusted source describes it and we assert NO model (spec Section 1).".to_string(),
        "Closed by understanding it or explicit Accepted -- never by aging out.".to_string(),
        String::new(),
    ];
    if n == 0 {
        lines.push("_empty_".to_string());
    }
    let ledger = m.semantic_ledger();
    for o in op_rows(&ledger, |r| r.verdict.is_comprehension_gap()) {
        lines.push(format!("{}: UNSPECIFIED", o.line()));
    }
    lines.push(String::new());
    format!("{}\n", lines.join("\n"))
}

/// Render the per-arch coverage matrix (spec Section 2 item 2, Section 7).
/// Replaces the hand-maintained docs/coverage/architecture-index.md. The
/// renderer owns the WHOLE file -- fixed preamble + mechanical matrix -- so
/// there is no hand-maintained prose to drift against stale data again (the
/// original failure mode, spec Problem statement).
pub fn render_architecture_index(arch: Architecture) -> String {
    let m = CoverageModel::build(arch);
    let mut lines = vec![
        format!("# {arch} architecture coverage index"),
        String::new(),
        "Generated by `cargo run -p xdna-archspec --example gen_coverage_artifacts`. Do not hand-edit."
            .to_string(),
        String::new(),
        "Mechanical Axis-2 coverage matrix: every SemanticOp category and its".to_string(),
        "rolled-up provenance/verification verdict. This file is generated from".to_string(),
        "the same CoverageModel that backs the semantic-provenance gate, so it".to_string(),
        "cannot silently disagree with `semantic_provenance_clean`.".to_string(),
        "Per-op overrides and the perishable/comprehension queues live in the".to_string(),
        "sibling perishable-queue.md / comprehension-gaps.md.".to_string(),
        "Each category lists the spine domains it tags; per-subsystem detail".to_string(),
        "is in the generated subsystem-index.md.".to_string(),
        String::new(),
        "| Category | Provenance | Verification | Domains |".to_string(),
        "|----------|------------|--------------|---------|".to_string(),
    ];
    // Every category, in a fixed order for determinism. The row verdict is the
    // worst-wins floor over the category's ops (m.category_verdict), NOT a
    // single representative -- so a heterogeneous category (some ops Verified by
    // a per-op override, some not) reports its honest floor here, while the
    // per-subsystem split surfaces in subsystem-index.md.
    let cats: &[Category] = &[
        Category::Arithmetic,
        Category::Bitwise,
        Category::Comparison,
        Category::Memory,
        Category::ControlFlow,
        Category::Vector,
        Category::Sync,
        Category::SideEffect,
        Category::NeedsTriage,
    ];
    for cat in cats {
        let v = m.category_verdict(*cat);
        let doms = category_domains(*cat);
        lines.push(format!(
            "| {cat:?} | {:?} | {:?} | {} |",
            v.provenance,
            v.verification,
            if doms.is_empty() {
                "-".to_string()
            } else {
                doms.join(", ")
            }
        ));
    }
    lines.push(String::new());
    format!("{}\n", lines.join("\n"))
}

/// Render the per-subsystem coverage index (spec Section 4): the retired
/// hand-maintained index's per-subsystem rows, regenerated.
pub fn render_subsystem_index(arch: Architecture) -> String {
    let mut lines = vec![
        format!("# {arch} subsystem coverage index"),
        String::new(),
        "Generated by `cargo run -p xdna-archspec --example gen_coverage_artifacts`. Do not hand-edit."
            .to_string(),
        String::new(),
        "Per-subsystem rows recovered from the retired hand-maintained index as".to_string(),
        "generated data (spec 2026-05-16-subsystem-axis-coverage-enrichment).".to_string(),
        "`rolled-up` is the worst-wins verdict of the categories tagged to the".to_string(),
        "domain, or `-` for category-orphan domains. Sibling queues:".to_string(),
        "implementation-gaps.md / perishable-queue.md / comprehension-gaps.md.".to_string(),
        String::new(),
        "| Domain | Source | Our location | Own verdict | Rolled-up | Drift | Narrative |".to_string(),
        "|--------|--------|--------------|-------------|-----------|-------|-----------|".to_string(),
    ];
    for d in capability_spine().into_iter().filter(|d| d.applies_to(arch)) {
        let rolled = match rolled_up_verdict(&d.id) {
            Some(v) => format!("{:?}/{:?}", v.provenance, v.verification),
            None => "-".to_string(),
        };
        let drift = if is_category_orphan(&d.id) {
            "orphan".to_string()
        } else if unannotated_material_drift(&d.id) {
            "MATERIAL".to_string()
        } else if d.drift_rationale.is_some() {
            "annotated".to_string()
        } else {
            "ok".to_string()
        };
        let src = d.source_ref.replace('|', "\\|");
        let locs_cell = if d.src_locations.is_empty() {
            "-".to_string()
        } else {
            d.src_locations.join(", ").replace('|', "\\|")
        };
        lines.push(format!(
            "| {} | {} | {} | {:?}/{:?} | {} | {} | {} |",
            d.id,
            src,
            locs_cell,
            d.verdict.provenance,
            d.verdict.verification,
            rolled,
            drift,
            d.narrative.replace('|', "\\|").replace('\n', " ")
        ));
    }
    lines.push(String::new());
    format!("{}\n", lines.join("\n"))
}

/// Render the implementation-gap queue (spec Section 4): domains whose own
/// seeded verdict is a `Modeled{Partial|Stub}` (or explicit MISSING). Sourced
/// from `capability_spine()` domain verdicts -- NEVER a category rollup, which
/// can never be `Modeled` (a permanently empty queue otherwise -- spec S1/M1).
pub fn render_implementation_gaps(arch: Architecture) -> String {
    let mut lines = vec![
        format!("# Implementation gaps ({arch})"),
        String::new(),
        "Generated by `cargo run -p xdna-archspec --example gen_coverage_artifacts`. Do not hand-edit."
            .to_string(),
        String::new(),
        "Subsystems only partially built or stubbed (spec Section 1, third gap".to_string(),
        "class). Empty == every named subsystem is Full/closed for this arch.".to_string(),
        String::new(),
    ];
    let gaps: Vec<_> = capability_spine()
        .into_iter()
        .filter(|d| d.applies_to(arch) && d.verdict.is_implementation_gap())
        .collect();
    if gaps.is_empty() {
        lines.push("_empty_".to_string());
    } else {
        for d in gaps {
            let what = match &d.verdict.verification {
                Verification::Modeled { completeness: Completeness::Partial { missing } } => {
                    format!("PARTIAL -- missing: {missing}")
                }
                Verification::Modeled { completeness: Completeness::Stub } => "STUB".to_string(),
                Verification::Modeled { completeness: Completeness::Full } => {
                    unreachable!("is_implementation_gap() filter should have excluded Modeled/Full")
                }
                Verification::NotApplicable
                | Verification::Verified { .. }
                | Verification::Unverified
                | Verification::Contradicted { .. }
                | Verification::Accepted { .. } => {
                    unreachable!(
                        "is_implementation_gap() filter should have excluded non-Modeled verifications"
                    )
                }
            };
            lines.push(format!("- {}: {what}", d.id));
        }
    }
    lines.push(String::new());
    format!("{}\n", lines.join("\n"))
}

