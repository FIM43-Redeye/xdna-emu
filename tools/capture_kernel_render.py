"""Shared rendering for single-purpose silicon capture kernels.

The kernels generated by gen_acc_addsub_f32.py and gen_vshift_wide.py share one
shape: a single compute tile consumes N chunks of 32-bit words and produces N
chunks of 32-bit words, and the host dumps the raw output words to out.txt
(one integer per line) before comparing them with the silicon golden. Only the
kernel body and the data differ, so the aie.mlir, run.lit, test.cpp and golden
writer live here.

Every buffer is a flat array of 32-bit words. The MLIR element type (f32 or i32)
is only a label for the compiler; the host never interprets the words.
"""

import json
import os


def c_array(name, ctype, values, per_line=8):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "static const %s %s[%d] = {\n%s\n};\n" % (ctype, name, len(values), "\n".join(lines))


def render_run_lit(kernel_cc):
    return f"""// (c) Copyright 2026 -- xdna-emu vector-compute verification.
// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
//
// REQUIRES: ryzen_ai_npu1, chess
//
// RUN: xchesscc_wrapper aie2 -I %aietools/include -c %S/{kernel_cc} -o ./kernel.o
// RUN: %aiecc --xchesscc --xbridge --get-xclbin --get-npu-insts --xclbin-name=aie.xclbin --npu-insts-name=insts.bin %S/aie.mlir
// RUN: clang %S/test.cpp -o test.exe -std=c++17 -Wall %xrt_flags -lrt -lstdc++ %test_utils_flags
// RUN: %run_on_npu1% ./test.exe -x aie.xclbin -k MLIR_AIE -i insts.bin
"""


def render_mlir(kernel, symbol, chunks, nin, nout, elem_in, elem_out, summary):
    return f"""//===- aie.mlir ------------------------------------------------*- MLIR -*-===//
//
// {kernel} capture design (GENERATED). One compute tile (0,2) consumes
// {chunks} chunks of {nin} words and produces {nout} words per chunk.
// {summary}
//
//===----------------------------------------------------------------------===//

module {{
  aie.device(npu1_1col) {{
    func.func private @{symbol}(memref<{nin}x{elem_in}>, memref<{nout}x{elem_out}>)
        attributes {{link_with = "kernel.o"}}

    %shim = aie.tile(0, 0)
    %core = aie.tile(0, 2)

    aie.objectfifo @inA(%shim, {{%core}}, 1 : i32) : !aie.objectfifo<memref<{nin}x{elem_in}>>
    aie.objectfifo @outC(%core, {{%shim}}, 1 : i32) : !aie.objectfifo<memref<{nout}x{elem_out}>>

    %core_0_2 = aie.core(%core) {{
      %c0 = arith.constant 0 : index
      %c1 = arith.constant 1 : index
      %cn = arith.constant {chunks} : index
      scf.for %i = %c0 to %cn step %c1 {{
        %a = aie.objectfifo.acquire @inA(Consume, 1) : memref<{nin}x{elem_in}>
        %o = aie.objectfifo.acquire @outC(Produce, 1) : memref<{nout}x{elem_out}>
        func.call @{symbol}(%a, %o) : (memref<{nin}x{elem_in}>, memref<{nout}x{elem_out}>) -> ()
        aie.objectfifo.release @inA(Consume, 1)
        aie.objectfifo.release @outC(Produce, 1)
      }}
      aie.end
    }}

    aie.runtime_sequence @sequence(%a: memref<{chunks * nin}x{elem_in}>, %o: memref<{chunks * nout}x{elem_out}>) {{
      aiex.npu.dma_memcpy_nd(%a[0, 0, 0, 0][{chunks}, 1, 1, {nin}][{nin}, 0, 0, 1]) {{id = 0 : i64, metadata = @inA}} : memref<{chunks * nin}x{elem_in}>
      aiex.npu.dma_memcpy_nd(%o[0, 0, 0, 0][{chunks}, 1, 1, {nout}][{nout}, 0, 0, 1]) {{id = 1 : i64, metadata = @outC}} : memref<{chunks * nout}x{elem_out}>
      aiex.npu.dma_wait {{symbol = @outC}}
    }}
  }}
}}
"""


def render_test_cpp(kernel, generator, in_words, expected):
    """Host harness: feed in_words, dump raw output to out.txt, compare to expected."""
    nin_total = len(in_words)
    nout_total = len(expected)
    return f"""//===- test.cpp -------------------------------------------------*- C++ -*-===//
//
// Host harness for {kernel} (GENERATED by tools/{generator}).
// Feeds the designed batch and checks every output word against the values
// observed on NPU1 (Phoenix) silicon (tools/golden/silicon/{kernel}.json).
//
//===----------------------------------------------------------------------===//

#include <algorithm>
#include <cstdint>
#include <cstring>
#include <fstream>
#include <iostream>
#include <vector>

#include "xrt/xrt_bo.h"
#include "xrt/xrt_device.h"
#include "xrt/xrt_kernel.h"

#include "test_utils.h"

static constexpr int NIN = {nin_total};
static constexpr int NOUT = {nout_total};

{c_array("IN", "uint32_t", in_words)}
{c_array("EXP", "uint32_t", expected)}
int main(int argc, const char *argv[]) {{
  std::vector<uint32_t> instr_v = test_utils::load_instr_binary("insts.bin");
  auto device = xrt::device(0u);
  xrt::xclbin xclbin(std::string("aie.xclbin"));
  auto xkernels = xclbin.get_kernels();
  auto xkernel = *std::find_if(xkernels.begin(), xkernels.end(),
                               [](xrt::xclbin::kernel &k) {{
                                 return k.get_name().rfind("MLIR_AIE", 0) == 0;
                               }});
  device.register_xclbin(xclbin);
  xrt::hw_context context(device, xclbin.get_uuid());
  auto kernel = xrt::kernel(context, xkernel.get_name());

  auto bo_instr = xrt::bo(device, instr_v.size() * sizeof(int), XCL_BO_FLAGS_CACHEABLE, kernel.group_id(1));
  auto bo_in = xrt::bo(device, NIN * sizeof(uint32_t), XRT_BO_FLAGS_HOST_ONLY, kernel.group_id(3));
  auto bo_out = xrt::bo(device, NOUT * sizeof(uint32_t), XRT_BO_FLAGS_HOST_ONLY, kernel.group_id(4));

  std::memcpy(bo_in.map<void *>(), IN, sizeof(IN));
  std::memset(bo_out.map<void *>(), 0, NOUT * sizeof(uint32_t));
  std::memcpy(bo_instr.map<void *>(), instr_v.data(), instr_v.size() * sizeof(int));

  bo_instr.sync(XCL_BO_SYNC_BO_TO_DEVICE);
  bo_in.sync(XCL_BO_SYNC_BO_TO_DEVICE);
  bo_out.sync(XCL_BO_SYNC_BO_TO_DEVICE);

  auto run = kernel(3, bo_instr, instr_v.size(), bo_in, bo_out);
  ert_cmd_state r = run.wait();
  if (r != ERT_CMD_STATE_COMPLETED) {{
    std::cout << "Kernel did not complete. Status: " << r << "\\n";
    return 1;
  }}
  bo_out.sync(XCL_BO_SYNC_BO_FROM_DEVICE);

  // Always dump the raw output (one value per line) so a HW run can be captured
  // as a silicon golden ({generator} capture).
  uint32_t *out = bo_out.map<uint32_t *>();
  {{
    std::ofstream dump("out.txt");
    for (int i = 0; i < NOUT; i++)
      dump << (int64_t)out[i] << "\\n";
  }}

  int errors = 0;
  for (int i = 0; i < NOUT; i++) {{
    if (out[i] != EXP[i]) {{
      if (errors < 10)
        std::cout << "Error [" << i << "]: got=" << out[i] << " != exp=" << EXP[i] << "\\n";
      errors++;
    }}
  }}
  if (!errors) {{
    std::cout << "\\nPASS!\\n\\n";
    return 0;
  }}
  std::cout << "\\nfailed (" << errors << " errors).\\n\\n";
  return 1;
}}
"""


def write_files(out_dir, files):
    os.makedirs(out_dir, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(out_dir, name), "w") as f:
            f.write(text)


def load_golden(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def read_out_txt(path):
    with open(path) as f:
        return [int(line) for line in f if line.strip()]


def write_golden(path, rec):
    """One top-level key per line, compact values (same layout as the D6 golden)."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("{\n")
        items = list(rec.items())
        for i, (k, v) in enumerate(items):
            f.write(json.dumps(k) + ": " + json.dumps(v, separators=(",", ":")))
            f.write(",\n" if i + 1 < len(items) else "\n")
        f.write("}\n")
    return path
