#!/usr/bin/env python3
"""Generate the wide VSHIFT / VSHIFT_ALIGN capture kernel (vec_vshift_wide).

Why this exists
---------------
`vshift d, s1, s2, r` and `vshift.align d, s1, s, s2, r` take two 512-bit x
registers and a byte-shift amount from a scalar register (the align form also
takes a small `s` register, the "step"). The emulator refuses the 512-bit forms,
and the narrow path that exists was never pinned on silicon. This kernel feeds
two vectors whose 128 bytes are all distinct and non-zero, so every output byte
names the input byte it came from (and a zero output byte is a zero fill), then
sweeps the shift amount (and the step) over the whole range the encoding takes,
including out-of-range and boundary values.

Chunk layout (32-bit words, all raw):
  [0..15]   A: 64 bytes, byte i = i + 1             (s1 operand)
  [16..31]  B: 64 bytes, byte i = 65 + i            (s2 operand)
  [32]      mode: 0 = vshift (plain), 1 = vshift.align
  [33]      reserved
  [34..161] 64 table entries of (step, shift)       (step ignored in mode 0)
Output per chunk: 64 entries x 16 words (one 64-byte vector per entry).

Usage
-----
  python3 tools/gen_vshift_wide.py generate          # run.lit, aie.mlir, kernel .cc
  python3 tools/stage_vector_kernel.py vec_vshift_wide   # no exp.bin yet
  # run the bridge on HW once (an uncaptured kernel fails by design; out.txt is
  # written first), then:
  python3 tools/gen_vshift_wide.py capture <build>/out.txt --date YYYY-MM-DD
  python3 tools/stage_vector_kernel.py vec_vshift_wide   # now stages exp.bin = silicon
"""

import argparse
import os
import random

import capture_kernel_render as render

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KERNEL = "vec_vshift_wide"
OUT_DIR = os.path.join(REPO, "tests", "vector-verify", KERNEL)
GOLDEN = os.path.join(REPO, "tools", "golden", "silicon", KERNEL + ".json")

ENTRIES = 64            # table entries per chunk
HEADER = 34             # words before the table
NIN = HEADER + 2 * ENTRIES
NOUT = ENTRIES * 16
MAX_CHUNKS = 64

M32 = 0xFFFFFFFF

# Shift amounts: every value 0..127, power-of-two and field boundaries, values
# with high bits set (does the hardware look at bits above the low six?), and
# negative amounts.
SHIFT_BOUNDARY = [128, 129, 130, 191, 192, 193, 255, 256, 257, 320, 511, 512, 513, 1000, 1023, 1024,
                  0x1000, 0x1005, 0xFFFF, 0x10000, 0x10005, 0x7FFFFFFF, 0x80000000, 0x80000005,
                  0x80000040, M32 - 63, M32 - 1, M32, (-64) & M32, (-5) & M32]
PLAIN_SHIFTS = list(range(0, 128)) + SHIFT_BOUNDARY

# Steps for the align form: small values densely, then field boundaries.
STEPS = list(range(0, 17)) + [31, 32, 33, 63, 64, 65, 127, 128, 255, 256, M32]
# Shifts for the align form: dense low range, byte-group boundaries, out of range.
ALIGN_SHIFTS = list(range(0, 68)) + [96, 127, 128, 129, 191, 192, 255, 256, 1000, M32]


def operand_bytes():
    a = [i + 1 for i in range(64)]
    b = [65 + i for i in range(64)]
    return a, b


def words_of(byte_list):
    return [byte_list[i] | byte_list[i + 1] << 8 | byte_list[i + 2] << 16 | byte_list[i + 3] << 24
            for i in range(0, len(byte_list), 4)]


def design():
    """The chunks: a list of (mode, [(step, shift) * ENTRIES])."""
    rng = random.Random(0x5B1F7)
    plain = [(0, s) for s in PLAIN_SHIFTS]
    while len(plain) % ENTRIES:
        plain.append((0, rng.choice((rng.randrange(0, 192), rng.randrange(1 << 32)))))
    align = [(st, sh) for st in STEPS for sh in ALIGN_SHIFTS]
    while len(align) % ENTRIES:
        align.append((rng.choice(STEPS), rng.choice((rng.randrange(0, 192), rng.randrange(1 << 32)))))
    chunks = [(0, plain[i:i + ENTRIES]) for i in range(0, len(plain), ENTRIES)]
    chunks += [(1, align[i:i + ENTRIES]) for i in range(0, len(align), ENTRIES)]
    assert len(chunks) <= MAX_CHUNKS, len(chunks)
    return chunks


def pack_input(chunks):
    a, b = operand_bytes()
    words = []
    for mode, entries in chunks:
        words += words_of(a) + words_of(b) + [mode, 0]
        for step, shift in entries:
            words += [step & M32, shift & M32]
    assert len(words) == len(chunks) * NIN
    return words


def render_kernel():
    return f"""//===- vshift_wide.cc -------------------------------------------*- C++ -*-===//
//
// Wide VSHIFT / VSHIFT_ALIGN capture kernel (GENERATED by tools/gen_vshift_wide.py).
// One chunk: A (64 bytes), B (64 bytes), a mode word, then {ENTRIES} (step, shift)
// entries; mode 0 runs the plain vshift, mode 1 the vshift.align with a runtime
// step. Each entry writes one 64-byte result.
//
//===----------------------------------------------------------------------===//

#include <stdint.h>

#include <aie_api/aie.hpp>

#define ENTRIES {ENTRIES}

extern "C" {{

void vshift_wide(int32_t *restrict in, int32_t *restrict out) {{
  v64int8 a = *(v64int8 *)(in);
  v64int8 b = *(v64int8 *)(in + 16);
  int mode = in[32];
  int32_t *tab = in + {HEADER};
  v64int8 *o = (v64int8 *)out;
  event0();
  if (mode == 0) {{
    for (int i = 0; i < ENTRIES; i++)
      o[i] = shift_bytes(a, b, (unsigned int)tab[2 * i + 1]);
  }} else {{
    for (int i = 0; i < ENTRIES; i++)
      o[i] = shiftx(a, b, tab[2 * i], (unsigned int)tab[2 * i + 1]);
  }}
  event1();
}}

}} // extern "C"
"""


def expected_words():
    """The silicon golden's output words, or None before the first capture."""
    golden = render.load_golden(GOLDEN)
    return None if golden is None else golden["silicon"]


def kernel_data():
    """Raw input and expected buffers (see vv_data.KernelData) for staging."""
    chunks = design()
    golden = render.load_golden(GOLDEN)
    in_words = pack_input(chunks)
    if golden is not None and golden["inputs"] != [in_words]:
        raise SystemExit("golden inputs are stale: the design changed; recapture on silicon")
    expected = expected_words()
    assert expected is None or len(expected) == len(chunks) * NOUT
    return render.kernel_data(in_words, expected)


def generate(out_dir=OUT_DIR):
    chunks = design()
    n_out = len(chunks) * NOUT
    kernel_data()   # fails on a stale golden before anything is written
    files = {
        "vshift_wide.cc": render_kernel(),
        "aie.mlir": render.render_mlir(
            KERNEL, "vshift_wide", len(chunks), NIN, NOUT, "i32", "i32",
            f"Chunk = A, B, mode, {ENTRIES} (step, shift) entries; {ENTRIES} x 64-byte results."),
        "run.lit": render.render_run_lit("vshift_wide.cc", n_out),
    }
    render.write_files(out_dir, files)
    return files


def capture(out_txt, date, golden_path=GOLDEN):
    chunks = design()
    silicon = [v & M32 for v in render.read_out_txt(out_txt)]
    n_out = len(chunks) * NOUT
    assert len(silicon) == n_out, f"{len(silicon)} != {n_out}"
    a, b = operand_bytes()
    rec = {
        "kernel": KERNEL, "class": "vshift_wide", "n": n_out,
        "operands": {"a": a, "b": b},
        "chunks": [{"mode": mode, "entries": [[st, sh] for st, sh in entries]} for mode, entries in chunks],
        "inputs": [pack_input(chunks)], "silicon": silicon,
        "provenance": f"HW-observed: NPU1 Phoenix silicon, captured {date} via tools/gen_vshift_wide.py",
    }
    return render.write_golden(golden_path, rec)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("generate")
    cap = sub.add_parser("capture")
    cap.add_argument("out_txt")
    cap.add_argument("--date", required=True)
    args = ap.parse_args(argv)
    if args.cmd == "generate":
        files = generate()
        print(f"wrote {len(files)} files to {OUT_DIR} ({len(design())} chunks)")
    else:
        print("wrote", capture(args.out_txt, args.date))


if __name__ == "__main__":
    main()
