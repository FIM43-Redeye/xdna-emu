"""Locate the sibling mlir-aie checkout the same way the Rust side does.

Mirrors crates/xdna-archspec/src/toolchain_paths.rs for mlir-aie:

  1. MLIR_AIE_PATH (alias MLIR_AIE_DIR)
  2. NPU_WORK_DIR/mlir-aie
  3. the nearest ancestor of ``start`` that contains a valid ``mlir-aie``

An explicit path (1 or 2) fails closed: if it does not validate, we raise
rather than silently falling through to discovery. Ancestor discovery walks
up, so a checkout inside ``.worktrees/<name>/`` still finds the workspace's
mlir-aie rather than looking for ``.worktrees/mlir-aie``.
"""

import os
from pathlib import Path

# A real mlir-aie clone carries the AM025 register database here; a stray
# directory that merely shares the name does not.
MLIR_AIE_SENTINEL = Path("lib/Dialect/AIE/Util/aie_registers_aie2.json")

# Header generated by the mlir-aie build, used by the trace tools.
EVENTS_HEADER_REL = Path(
    "build/include/xaienginecdo_static/xaiengine/xaie_events_aieml.h")


class ToolchainPathError(RuntimeError):
    """mlir-aie could not be located or the selected path is invalid."""


def _validate(candidate, source):
    candidate = Path(candidate)
    if not candidate.is_dir():
        raise ToolchainPathError(
            f"mlir-aie path selected by {source} is not a directory: {candidate}")
    sentinel = candidate / MLIR_AIE_SENTINEL
    if not sentinel.is_file():
        raise ToolchainPathError(
            f"mlir-aie path selected by {source} is missing required "
            f"sentinel {MLIR_AIE_SENTINEL}: {sentinel}")
    return candidate.resolve()


def resolve_mlir_aie(start=None, env=None):
    """Return the mlir-aie root. ``start`` is any path inside the checkout
    (default: this file); ``env`` defaults to ``os.environ``."""
    env = os.environ if env is None else env
    for name in ("MLIR_AIE_PATH", "MLIR_AIE_DIR"):
        if name in env:
            if not env[name]:
                raise ToolchainPathError(
                    f"mlir-aie path selected by {name} is blank")
            return _validate(env[name], name)
    if "NPU_WORK_DIR" in env:
        if not env["NPU_WORK_DIR"]:
            raise ToolchainPathError(
                "mlir-aie path selected by NPU_WORK_DIR is blank")
        return _validate(Path(env["NPU_WORK_DIR"]) / "mlir-aie", "NPU_WORK_DIR")

    here = Path(start if start is not None else __file__).resolve()
    for ancestor in (here, *here.parents):
        candidate = ancestor / "mlir-aie"
        if (candidate / MLIR_AIE_SENTINEL).is_file():
            return candidate.resolve()
    raise ToolchainPathError(
        "mlir-aie was not found by ancestor discovery from "
        f"{here}; set MLIR_AIE_PATH or NPU_WORK_DIR")


def try_resolve_mlir_aie(start=None, env=None):
    """``resolve_mlir_aie`` for callers that can run without mlir-aie (tests
    that skip when it is absent): None instead of raising."""
    try:
        return resolve_mlir_aie(start, env)
    except ToolchainPathError:
        return None


def events_header(start=None, env=None):
    """Path of xaie_events_aieml.h under the resolved mlir-aie."""
    return resolve_mlir_aie(start, env) / EVENTS_HEADER_REL


def find_workspace_dir(name, start=None, env=None):
    """Locate a sibling workspace directory (e.g. ``xdna-emu-priv``) the same
    way: ``NPU_WORK_DIR/<name>`` if set, else the nearest ancestor of
    ``start`` containing ``<name>``. Returns None when it is not there, since
    callers of sibling repos (private companions) must tolerate absence."""
    env = os.environ if env is None else env
    if env.get("NPU_WORK_DIR"):
        candidate = Path(env["NPU_WORK_DIR"]) / name
        return candidate.resolve() if candidate.is_dir() else None
    here = Path(start if start is not None else __file__).resolve()
    for ancestor in (here, *here.parents):
        if (ancestor / name).is_dir():
            return (ancestor / name).resolve()
    return None


def workspace_root(start=None, env=None):
    """The workspace directory that holds xdna-emu and its sibling repos:
    ``NPU_WORK_DIR`` if set, else the ancestor containing ``xdna-emu``
    (which also holds from inside ``xdna-emu/.worktrees/<name>/``).
    Raises ToolchainPathError when neither applies."""
    env = os.environ if env is None else env
    if env.get("NPU_WORK_DIR"):
        return Path(env["NPU_WORK_DIR"]).resolve()
    emu = find_workspace_dir("xdna-emu", start, {})
    if emu is None:
        raise ToolchainPathError(
            "workspace root not found: set NPU_WORK_DIR or run from a "
            "checkout inside a workspace holding xdna-emu")
    return emu.parent
