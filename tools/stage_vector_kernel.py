#!/usr/bin/env python3
"""Stage vector-verify kernels into the mlir-aie clone for the bridge harness.

The committed kernel directories under tests/vector-verify/ carry no data and no
host program. The bridge harness (scripts/emu-bridge-test.sh) discovers tests
only under $MLIR_AIE/test/npu-xrt/ and needs a test.cpp there, so this tool
assembles each kernel's runnable form:

  1. copies the kernel directory (run.lit, aie.mlir, the kernel .cc);
  2. copies tests/vector-verify/common/vv_host.cpp in as test.cpp;
  3. writes the data the host loads at runtime, from the golden JSON in
     tools/golden/silicon/ (the single source of truth): in0.bin, in1.bin, ...
     and exp.bin. A kernel with no silicon capture yet gets no exp.bin, which is
     the bootstrap state: it runs on HW, dumps out.txt and fails by design.

Usage:
  python3 tools/stage_vector_kernel.py vec_srs_i32 vec_mac_i8   # named kernels
  python3 tools/stage_vector_kernel.py --all
  python3 tools/stage_vector_kernel.py --clean      # remove every staged copy

MLIR_AIE is resolved like scripts/emu-bridge-test.sh: $MLIR_AIE, else
$NPU_WORK_DIR/mlir-aie, else the nearest ancestor of this checkout that has an
mlir-aie directory (so it also works from a git worktree).

--clean removes the staged directory and its bridge build output
(mlir-aie/build/test/npu-xrt/<kernel>) for every kernel this tool can stage.
Kernels it cannot stage (hand-written ones that still carry their own test.cpp)
are never touched.
"""

import argparse
import os
import shutil
import sys

import vv_data

TOOLS = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(TOOLS)
KERNEL_ROOT = os.path.join(REPO, "tests", "vector-verify")
HOST_SOURCE = os.path.join(KERNEL_ROOT, "common", "vv_host.cpp")


def mlir_aie_dir():
    """The mlir-aie clone, resolved the way scripts/emu-bridge-test.sh does."""
    env = os.environ.get("MLIR_AIE")
    if env:
        return env
    work = os.environ.get("NPU_WORK_DIR")
    if work:
        return os.path.join(work, "mlir-aie")
    here = REPO
    while True:
        cand = os.path.join(here, "mlir-aie")
        if os.path.isdir(cand):
            return cand
        parent = os.path.dirname(here)
        if parent == here:
            raise SystemExit("cannot find mlir-aie: set MLIR_AIE or NPU_WORK_DIR")
        here = parent


def data_sources():
    """Kernel name -> zero-argument function returning its `vv_data.KernelData`.

    Every generator contributes the kernels it owns; the data function is the
    same one the generator's own code paths use.
    """
    import gen_acc_addsub_f32
    import gen_agu_2d3d
    import gen_mac_bf16_forms
    import gen_mac_modes
    import gen_vector_kernel
    import gen_vldb_unpack
    import gen_vshift_wide
    from vector_kernel_specs import SPECS, SWEEPS

    sources = {}
    specs = dict(SPECS)
    for sweep in SWEEPS.values():
        for point in sweep.expand():
            specs[point.name] = point
    for name, spec in specs.items():
        sources[name] = (lambda spec=spec: gen_vector_kernel.kernel_data(spec))
    for module in (gen_acc_addsub_f32, gen_mac_bf16_forms, gen_vshift_wide):
        assert module.KERNEL not in sources, module.KERNEL
        sources[module.KERNEL] = module.kernel_data
    for mode in gen_mac_modes.MODES:
        for kind in gen_mac_modes.SHAPES:
            name = gen_mac_modes.kernel_name(mode, kind)
            assert name not in sources, name
            sources[name] = (lambda mode=mode, kind=kind: gen_mac_modes.kernel_data(mode, kind))
    for name in gen_vldb_unpack.kernel_names():
        assert name not in sources, name
        sources[name] = (lambda name=name: gen_vldb_unpack.kernel_data(name))
    for name in gen_agu_2d3d.kernel_names():
        assert name not in sources, name
        sources[name] = (lambda name=name: gen_agu_2d3d.kernel_data(name))
    return sources


def staged_dir(kernel, mlir_aie=None):
    return os.path.join(mlir_aie or mlir_aie_dir(), "test", "npu-xrt", kernel)


def stage(kernel, sources, mlir_aie=None):
    """Assemble one kernel's staged directory; return its path."""
    if kernel not in sources:
        raise SystemExit(f"unknown kernel '{kernel}' (not generated by a data-driven generator)")
    src = os.path.join(KERNEL_ROOT, kernel)
    if not os.path.isdir(src):
        raise SystemExit(f"{src} does not exist; run its generator first")
    data = sources[kernel]()   # before touching the destination: a stale golden aborts cleanly
    dest = staged_dir(kernel, mlir_aie)
    if os.path.isdir(dest):
        shutil.rmtree(dest)
    shutil.copytree(src, dest)
    shutil.copyfile(HOST_SOURCE, os.path.join(dest, "test.cpp"))
    vv_data.write_data(dest, data)
    return dest


def clean(sources, mlir_aie=None):
    """Remove staged copies and their bridge build output; return what was removed."""
    root = mlir_aie or mlir_aie_dir()
    removed = []
    for kernel in sorted(sources):
        for path in (staged_dir(kernel, root),
                     os.path.join(root, "build", "test", "npu-xrt", kernel)):
            if os.path.isdir(path):
                shutil.rmtree(path)
                removed.append(path)
    return removed


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Stage vector-verify kernels (kernel dir + shared host + data).")
    ap.add_argument("kernel", nargs="*", help="kernel directory names under tests/vector-verify")
    ap.add_argument("--all", action="store_true", help="stage every data-driven kernel")
    ap.add_argument("--clean", action="store_true",
                    help="remove staged copies and their bridge build output")
    args = ap.parse_args(argv)

    sources = data_sources()
    if args.clean:
        if args.kernel or args.all:
            ap.error("--clean takes no kernel names and cannot combine with --all")
        for path in clean(sources):
            print(f"removed {path}")
        return 0
    names = sorted(sources) if args.all else args.kernel
    if not names:
        ap.error("name at least one kernel, or pass --all / --clean")
    for kernel in names:
        dest = stage(kernel, sources)
        has_exp = os.path.exists(os.path.join(dest, vv_data.EXP_NAME))
        print(f"staged {kernel} -> {dest}" + ("" if has_exp else "  (no exp.bin: uncaptured)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
