const OLD: [u64; 8] = [0x01; 8];
const NEW: [u64; 8] = [0x02; 8];
const PRODUCER_BUNDLE: i64 = 4;

fn info_of<'a>(infos: &'a [InstrInfo], name: &str) -> &'a InstrInfo {
    infos
        .iter()
        .enumerate()
        .find(|(i, _)| opcode_name(*i as u32).as_deref() == Some(name))
        .map(|(_, info)| info)
        .unwrap_or_else(|| panic!("opcode {name} not in the decoder"))
}

/// Whether a consumer of `(use_cycle, use_bypass)` issued at `consumer_bundle` reads the
/// producer's value, with the producer issued at `PRODUCER_BUNDLE`.
fn consumer_sees_new(
    l_def: u8,
    def_bypass: Bypass,
    use_cycle: u8,
    use_bypass: Bypass,
    consumer_bundle: i64,
) -> bool {
    let mut rf = AccumulatorRegisterFile::new();
    rf.write(0, OLD);
    rf.advance_bundle(PRODUCER_BUNDLE as u64);
    rf.queue_write(0, NEW, l_def, def_bypass);
    // A source read at a cycle beyond the store/SRS/move one is performed at that cycle, with the
    // use cycle elapsed (how the MAC and accumulator add/sub are executed); the others read at
    // issue.
    let (read_bundle, rest) = if use_cycle > ACC_STORE_USE_CYCLE {
        (consumer_bundle + use_cycle as i64, 0)
    } else {
        (consumer_bundle, use_cycle)
    };
    if read_bundle < PRODUCER_BUNDLE {
        return false; // read before the producer exists
    }
    rf.advance_bundle(read_bundle as u64);
    rf.read_with(0, rest, use_bypass) == NEW
}

#[test]
fn the_register_file_reproduces_every_silicon_threshold() {
    let infos = query_all_instr_info();
    assert!(!infos.is_empty(), "decoder tables not available");
    let mut wrong = Vec::new();
    for &(producer, consumer, acc_idx, silicon_t) in SILICON_THRESHOLDS {
        let p = info_of(&infos, producer);
        let c = info_of(&infos, consumer);
        let l_def = p.operand_cycle[0] as u8;
        let def_bypass = Bypass::from_forwarding_id(p.operand_bypass[0]);
        let use_cycle = c.use_cycle(acc_idx);
        let use_bypass = Bypass::from_forwarding_id(c.use_bypass_raw(acc_idx));
        // smallest signed distance at which the consumer sees NEW
        let model_t = (-6..=16)
            .find(|s| {
                consumer_sees_new(l_def, def_bypass, use_cycle, use_bypass, PRODUCER_BUNDLE + *s as i64)
            })
            .unwrap_or(99);
        if model_t != silicon_t {
            wrong.push(format!("{producer} -> {consumer}[{acc_idx}]: silicon {silicon_t}, model {model_t}"));
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {} thresholds differ:\n{}",
        wrong.len(),
        SILICON_THRESHOLDS.len(),
        wrong.join("\n")
    );
}

/// The rule in words, on hand-picked anchors independent of the table: an integer MAC result
/// reaches a store 5 bundles later, a dependent integer MAC 2 (forwarding), a float MAC's 6 and 4
/// (no forwarding), and a `vmov` result a store 2 and a MAC in the same bundle.
#[test]
fn anchors_of_the_visibility_rule() {
    let t = |l_def, db, u, ub| {
        (-6..=16)
            .find(|s| consumer_sees_new(l_def, db, u, ub, PRODUCER_BUNDLE + *s as i64))
            .unwrap()
    };
    assert_eq!(t(5, Bypass::Vec, 1, Bypass::No), 5);
    assert_eq!(t(5, Bypass::Vec, 3, Bypass::Vec), 2);
    assert_eq!(t(6, Bypass::No, 1, Bypass::No), 6);
    assert_eq!(t(6, Bypass::No, 3, Bypass::No), 4);
    assert_eq!(t(2, Bypass::No, 1, Bypass::No), 2);
    assert_eq!(t(2, Bypass::No, 3, Bypass::Vec), 0);
}
