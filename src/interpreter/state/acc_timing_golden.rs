//! Golden replay of the accumulator timing probe (`tools/gen_acc_timing_probe.py`).
//!
//! Every row is one producer/consumer pair swept on NPU1 silicon (two runs, bit-identical): the
//! consumer sees the producer's value from signed issue distance `t` on (`t` bundles after the
//! producer; the consumer issued before the producer is a negative distance). The test derives the
//! same threshold from the accumulator register file with the operand cycles and bypass ids of the
//! decoded instructions, so a change to the visibility rule, to the bypass mapping or to the
//! itinerary plumbing shows up here. Rows are generated by
//! `tools/fit_acc_timing.py <thresholds.json> --rust`.
//!
//! Single-point structural hazards the probe also saw (a `vmov` source read colliding with a
//! `vadd`/`vaddmac` read, a `vclr` write colliding with a float MAC write) are not modelled and
//! not in the table.

