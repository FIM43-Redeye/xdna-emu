/// TableGen classes whose leaves are the scrubbed registers.
const SOURCE_CLASSES: &[&str] = &["mMvSclDst", "mWm", "mAMm", "mQQm"];
/// TableGen class of the registers `lda` loads directly (`mLdaScl`, the destination of every
/// `lda` form); the other scalar-side registers are
/// loaded through a scalar register and a move.
const LOAD_CLASS: &str = "mLdaScl";

/// How the scrub kernel loads a register.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LoadKind {
    /// `lda <reg>, [p], #4`.
    Scalar,
    /// `lda r<k>`, then `mov <reg>, r<k>`.
    ViaScalar,
    /// `vlda <reg>, [p], #32`.
    Vector,
    /// `lda <reg>, [p], #16` (q registers).
    Quad,
}

/// One scrubbed register.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ScrubRegister {
    pub name: String,
    /// Width TableGen gives the register (narrowest class holding it).
    pub bits: u16,
    /// Bytes the table holds for it: 4 for scalar-side registers, else `bits / 8`.
    pub bytes: usize,
    pub load: LoadKind,
    /// Offset of its value in [`table`].
    pub offset: usize,
}

/// FNV-1a over the name: a stable per-register seed.
fn name_seed(name: &str) -> u64 {
    name.bytes()
        .fold(0xcbf2_9ce4_8422_2325u64, |h, b| (h ^ b as u64).wrapping_mul(0x0100_0000_01b3))
}

fn splitmix64(mut z: u64) -> u64 {
    z = z.wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// The pattern word `word` of register `name` (before the register's width masks it).
pub fn pattern_word(name: &str, word: usize) -> u32 {
    let seed = name_seed(name) ^ ((SCRUB_PATTERN_VERSION as u64) << 56) ^ word as u64;
    let mut v = splitmix64(seed) as u32;
    // A zero word would be indistinguishable from a cleared register.
    if v == 0 {
        v = 0x5C2B_5C2B;
    }
    v
}

/// The pattern bytes of register `name`, little-endian words.
pub fn pattern_bytes(name: &str, len: usize) -> Vec<u8> {
    (0..len.div_ceil(4))
        .flat_map(|w| pattern_word(name, w).to_le_bytes())
        .take(len)
        .collect()
}

fn derive_registers() -> Vec<ScrubRegister> {
    let model = xdna_archspec::aie2::isa::load_from_generated().register_model;
    // The leaf registers of a class in TableGen member order, member classes expanded in place.
    fn expand(model: &xdna_archspec::aie2::isa::RegisterModel, class: &str, out: &mut Vec<String>) {
        let def = model
            .classes
            .get(class)
            .unwrap_or_else(|| panic!("TableGen class {class} missing"));
        for m in &def.members {
            if model.classes.contains_key(m) {
                expand(model, m, out);
            } else {
                out.push(m.clone());
            }
        }
    }
    let leaves = |class: &str| {
        let mut out = Vec::new();
        expand(&model, class, &mut out);
        out
    };
    let loadable = leaves(LOAD_CLASS);
    let mut seen = std::collections::HashSet::new();
    let mut regs = Vec::new();
    for class in SOURCE_CLASSES {
        for def in leaves(class) {
            // the assembler's spelling (`ls` for the def `LS`); widths and classes use the def
            let name = model.registers.get(&def).map_or_else(|| def.clone(), |r| r.asm_name.clone());
            if EXCLUDED.iter().any(|(n, _)| *n == name) || !seen.insert(name.clone()) {
                continue;
            }
            let bits = model.register_width_bits(&def).unwrap_or_else(|| panic!("{def}: no width"));
            let (load, bytes) = match (*class, bits) {
                ("mMvSclDst", _) if loadable.contains(&def) => (LoadKind::Scalar, 4),
                ("mMvSclDst", _) => (LoadKind::ViaScalar, 4),
                ("mQQm", 128) => (LoadKind::Quad, 16),
                (_, 256) => (LoadKind::Vector, 32),
                _ => panic!("{name}: unexpected class {class} width {bits}"),
            };
            regs.push(ScrubRegister { name, bits, bytes, load, offset: 0 });
        }
    }
    // Table layout = load order, so one pointer walks it with post-increments: the registers
    // staged through scalar registers, the 32-byte vector values (aligned), q, the directly
    // loaded scalar-side registers, and last the pointers p0-p2 the kernel walks with.
    let rank = |r: &ScrubRegister| match (r.load, r.name.as_str()) {
        (_, "p0" | "p1" | "p2") => 4,
        (LoadKind::ViaScalar, _) => 0,
        (LoadKind::Vector, _) => 1,
        (LoadKind::Quad, _) => 2,
        (LoadKind::Scalar, _) => 3,
    };
    regs.sort_by_key(rank); // stable: TableGen order within a group
    let mut off = 0usize;
    for r in &mut regs {
        if r.load == LoadKind::Vector {
            off = off.next_multiple_of(32);
        }
        r.offset = off;
        off += r.bytes;
    }
    regs
}

/// The scrubbed registers, in table order.
pub fn scrub_registers() -> &'static [ScrubRegister] {
    static REGS: OnceLock<Vec<ScrubRegister>> = OnceLock::new();
    REGS.get_or_init(derive_registers)
}

/// The table the scrub kernel loads (its input buffer): every register's pattern at its offset.
pub fn table() -> Vec<u8> {
    let regs = scrub_registers();
    let end = regs.iter().map(|r| r.offset + r.bytes).max().unwrap_or(0).next_multiple_of(32);
    let mut t = vec![0u8; end];
    for r in regs {
        t[r.offset..r.offset + r.bytes].copy_from_slice(&pattern_bytes(&r.name, r.bytes));
    }
    t
}

/// Latency cover after a load before its destination is read.
const LOAD_NOPS: usize = 7;

/// The pointers the kernel walks the table with; loaded last.
const WALKERS: [&str; 3] = ["p0", "p1", "p2"];

/// The scrub kernel, `test_kernel(in, out)`: stores [`SCRUB_OUT_MARKER`] to `out`, then loads
/// every register of [`scrub_registers`] from `in` (= [`table`]) in table order through `p2`,
/// and returns. `p0`-`p2` come last, loaded through `p1`, which goes last of all.
pub fn kernel_asm() -> String {
    let regs = scrub_registers();
    let mut a: Vec<String> = vec![
        "// Generated by `cargo run --bin scrub-kernel` (src/interpreter/state/scrub.rs).".into(),
        format!(
            "// Scrub pattern {}: loads every register from the table, see the JSON.",
            scrub_pattern_name()
        ),
        ".text".into(),
        ".globl test_kernel".into(),
        ".p2align 4".into(),
        "test_kernel:".into(),
        format!("  movxm r0, #0x{SCRUB_OUT_MARKER:08x}"),
        "  mov p2, p0".into(),
    ];
    let nops = |a: &mut Vec<String>, n: usize| a.extend(std::iter::repeat_n("  nop".to_string(), n));
    nops(&mut a, 2);
    a.push("  st r0, [p1, #0]".into());
    let mut at = 0usize; // table offset p2 points at
    let seek = |a: &mut Vec<String>, at: &mut usize, to: usize| {
        if to != *at {
            a.push(format!("  padda [p2], #{}", to - *at));
            a.push("  nop".into());
            *at = to;
        }
    };
    let walked = |r: &&ScrubRegister| !WALKERS.contains(&r.name.as_str());
    // 1. staged through r0.. (the r file itself is loaded later)
    let staged: Vec<_> = regs.iter().filter(|r| r.load == LoadKind::ViaScalar).collect();
    for chunk in staged.chunks(16) {
        for (j, r) in chunk.iter().enumerate() {
            seek(&mut a, &mut at, r.offset);
            a.push(format!("  lda r{j}, [p2], #4"));
            at += 4;
        }
        nops(&mut a, LOAD_NOPS);
        for (j, r) in chunk.iter().enumerate() {
            a.push(format!("  mov {}, r{j}", r.name));
        }
        nops(&mut a, LOAD_NOPS);
    }
    // 2. everything else but the walkers, in table order
    for r in regs.iter().filter(|r| r.load != LoadKind::ViaScalar).filter(walked) {
        seek(&mut a, &mut at, r.offset);
        let line = match r.load {
            LoadKind::Vector => format!("  vlda {}, [p2], #32", r.name),
            LoadKind::Quad => format!("  lda {}, [p2], #16", r.name),
            _ => format!("  lda {}, [p2], #4", r.name),
        };
        a.push(line);
        at += r.bytes;
    }
    nops(&mut a, LOAD_NOPS);
    // 3. the walkers: p1 = p2 at their entries, then p0, p2, and p1 last (its own base)
    let off = |n: &str| regs.iter().find(|r| r.name == n).map(|r| r.offset);
    if let Some(base) = WALKERS.iter().filter_map(|n| off(n)).min() {
        seek(&mut a, &mut at, base);
        a.push("  mov p1, p2".into());
        nops(&mut a, 2);
        for n in ["p0", "p2", "p1"] {
            if let Some(o) = off(n) {
                a.push(format!("  lda {n}, [p1, #{}]", o - base));
            }
        }
    }
    nops(&mut a, LOAD_NOPS);
    a.push("  ret lr".into());
    nops(&mut a, 5);
    a.join("\n") + "\n"
}

/// The artifact the harness reads: pattern, layout, kernel source, exclusions.
pub fn artifact_json() -> serde_json::Value {
    let regs: Vec<_> = scrub_registers()
        .iter()
        .map(|r| {
            serde_json::json!({"name": r.name, "bits": r.bits, "bytes": r.bytes, "offset": r.offset,
                               "load": format!("{:?}", r.load)})
        })
        .collect();
    let excluded: Vec<_> = EXCLUDED
        .iter()
        .map(|(n, why)| serde_json::json!({"name": n, "reason": why}))
        .collect();
    let table: String = table().iter().map(|b| format!("{b:02x}")).collect();
    serde_json::json!({
        "format": 1,
        "name": scrub_pattern_name(),
        "version": SCRUB_PATTERN_VERSION,
        "out_marker": SCRUB_OUT_MARKER,
        "registers": regs,
        "excluded": excluded,
        "table_hex": table,
        "kernel_s": kernel_asm(),
    })
}

/// A core initialisation the emulator applies to every new core context.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CoreInit {
    /// The scrub pattern of this build ([`SCRUB_PATTERN_VERSION`]).
    Scrub,
}

impl CoreInit {
    /// `XDNA_EMU_CORE_INIT`: unset or empty = none; the current scrub pattern name selects
    /// [`CoreInit::Scrub`]. Any other value is a mismatch between the harness and this build
    /// and panics rather than run a case from the wrong state.
    pub fn from_env() -> Option<CoreInit> {
        match std::env::var("XDNA_EMU_CORE_INIT") {
            Err(_) => None,
            Ok(v) if v.is_empty() => None,
            Ok(v) if v == scrub_pattern_name() => Some(CoreInit::Scrub),
            Ok(v) => panic!(
                "XDNA_EMU_CORE_INIT={v}: this emulator knows only {} (pattern version mismatch?)",
                scrub_pattern_name()
            ),
        }
    }

    /// Write the initial values into `ctx`'s registers, as the scrub kernel leaves them.
    pub fn apply(self, ctx: &mut ExecutionContext) {
        match self {
            CoreInit::Scrub => apply_scrub(ctx),
        }
    }
}

fn apply_scrub(ctx: &mut ExecutionContext) {
    for r in scrub_registers() {
        let bytes = pattern_bytes(&r.name, r.bytes);
        let mapped = classify_reg_name(&r.name)
            .unwrap_or_else(|| panic!("scrub register {} has no emulator operand", r.name));
        let word = || u32::from_le_bytes(bytes[..4].try_into().unwrap());
        match (mapped.operand, r.load) {
            (Operand::ScalarReg(i), LoadKind::Scalar | LoadKind::ViaScalar) => ctx.scalar.write(i, word()),
            (Operand::PointerReg(i), LoadKind::Scalar) => ctx.pointer.write(i, word()),
            (Operand::ModifierReg(i), LoadKind::Scalar) => ctx.modifier.write(i, word()),
            (Operand::VectorReg(i), LoadKind::Vector) => {
                ctx.vector.write_bytes(i, bytes.as_slice().try_into().unwrap())
            }
            (Operand::AccumReg(i), LoadKind::Vector) => {
                let (shift, lanes) = match mapped.accum_width {
                    Some(AccumWidth::QuarterLow) => (0, 0x0F),
                    Some(AccumWidth::QuarterHigh) => (4, 0xF0),
                    w => panic!("{}: accumulator quarter expected, got {w:?}", r.name),
                };
                let mut value = [0u64; 8];
                for (k, chunk) in bytes.chunks_exact(8).enumerate() {
                    value[shift + k] = u64::from_le_bytes(chunk.try_into().unwrap());
                }
                ctx.accumulator.write_lanes(i, &value, lanes);
            }
            (Operand::ControlReg(i), LoadKind::Quad) => {
                let q = i - super::registers::CTRL_BASE_Q;
                let mut v = [0u32; 4];
                for (k, chunk) in bytes.chunks_exact(4).enumerate() {
                    v[k] = u32::from_le_bytes(chunk.try_into().unwrap());
                }
                ctx.mask.write(q, v);
            }
            (op, load) => panic!("scrub register {}: operand {op:?} with load {load:?}", r.name),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_register_list_is_every_writable_core_register_minus_the_exclusions() {
        let names: Vec<&str> = scrub_registers().iter().map(|r| r.name.as_str()).collect();
        let count = |p: &str| {
            names
                .iter()
                .filter(|n| n.strip_prefix(p).is_some_and(|d| d.parse::<u8>().is_ok()))
                .count()
        };
        assert_eq!(count("r"), 31, "r0-r31 minus r16");
        assert!(!names.contains(&"r16"));
        assert_eq!(count("p"), 8);
        for f in ["m", "dn", "dj", "dc"] {
            assert_eq!(count(f), 8, "{f}");
        }
        assert_eq!(count("s"), 4);
        for n in ["ls", "lc", "dp"] {
            assert!(names.contains(&n), "{n}");
        }
        assert_eq!(count("wl") + count("wh"), 24);
        assert_eq!(count("amll") + count("amlh") + count("amhl") + count("amhh"), 36);
        assert_eq!(count("q"), 4);
        for (n, _) in EXCLUDED {
            assert!(!names.contains(n), "{n} is excluded");
        }
        assert!(!names.iter().any(|n| n.starts_with("cr") || n.starts_with("sr")));
        assert!(!names.contains(&"CORE_ID"), "read-only, not in mMvSclDst");
    }

    #[test]
    fn widths_and_load_kinds_come_from_tablegen() {
        let get = |n: &str| scrub_registers().iter().find(|r| r.name == n).unwrap().clone();
        assert_eq!((get("r3").bits, get("r3").load), (32, LoadKind::Scalar));
        assert_eq!((get("p5").bits, get("p5").load), (20, LoadKind::Scalar));
        assert_eq!(get("lc").load, LoadKind::ViaScalar, "lc is not in mLdaScl");
        assert_eq!(get("s2").load, LoadKind::ViaScalar);
        assert_eq!(get("ls").load, LoadKind::ViaScalar);
        assert_eq!((get("wh7").bits, get("wh7").load), (256, LoadKind::Vector));
        assert_eq!((get("amhl8").bits, get("amhl8").bytes), (256, 32));
        assert_eq!((get("q3").load, get("q3").bytes), (LoadKind::Quad, 16));
    }

    #[test]
    fn the_pattern_is_deterministic_nonzero_and_differs_per_register_and_word() {
        assert_eq!(pattern_bytes("wl3", 32), pattern_bytes("wl3", 32));
        assert_ne!(pattern_bytes("wl3", 32), pattern_bytes("wl4", 32));
        let words: Vec<u32> = (0..8).map(|w| pattern_word("amll0", w)).collect();
        let distinct: std::collections::HashSet<_> = words.iter().collect();
        assert_eq!(distinct.len(), 8, "no repeated constant inside a register");
        let mut all = std::collections::HashSet::new();
        for r in scrub_registers() {
            for w in 0..r.bytes / 4 {
                let v = pattern_word(&r.name, w);
                assert_ne!(v, 0);
                assert!(all.insert(v), "{} word {w} repeats another register's word", r.name);
            }
        }
    }

    #[test]
    fn the_table_holds_each_register_at_its_offset_and_vectors_are_aligned() {
        let t = table();
        for r in scrub_registers() {
            assert_eq!(
                &t[r.offset..r.offset + r.bytes],
                pattern_bytes(&r.name, r.bytes).as_slice(),
                "{}",
                r.name
            );
            if r.load == LoadKind::Vector {
                assert_eq!(r.offset % 32, 0, "{}", r.name);
            }
        }
        assert_eq!(t.len() % 32, 0);
    }

    #[test]
    fn the_kernel_loads_every_register_once_and_never_touches_the_exclusions() {
        let asm = kernel_asm();
        for r in scrub_registers() {
            let as_dest = asm
                .lines()
                .filter(|l| {
                    let l = l.trim();
                    (l.starts_with("lda ") || l.starts_with("vlda ") || l.starts_with("mov "))
                        && l.split_whitespace().nth(1) == Some(&format!("{},", r.name))
                })
                .count();
            // r scratch registers (staging) and the walkers are written more than once
            let multi = r.name.starts_with('r') || WALKERS.contains(&r.name.as_str());
            assert!(as_dest >= 1, "{} never loaded", r.name);
            assert!(multi || as_dest == 1, "{} loaded {as_dest} times", r.name);
        }
        for (n, _) in EXCLUDED {
            let dest = asm.lines().any(|l| l.split_whitespace().nth(1) == Some(&format!("{n},")));
            assert!(!dest, "{n} is written by the kernel");
        }
        assert!(asm.contains("ret lr"));
    }

    #[test]
    fn applying_the_scrub_leaves_the_table_values_in_the_context() {
        let mut ctx = ExecutionContext::new();
        CoreInit::Scrub.apply(&mut ctx);
        let word = |n: &str| pattern_word(n, 0);
        assert_eq!(ctx.scalar.read(5), word("r5"));
        assert_eq!(ctx.pointer.read(3), word("p3") & 0xF_FFFF);
        assert_eq!(ctx.scalar.read(super::super::registers::LC_REG_INDEX), word("lc"));
        assert_eq!(ctx.scalar.read(super::super::registers::SHIFT_REG_BASE + 1), word("s1") & 0x3F);
        let wh2 = ctx.vector.read(5);
        assert_eq!(wh2[0], word("wh2"));
        assert_eq!(wh2[7], pattern_word("wh2", 7));
        // amhl3 = lanes 0-3 of bmh3 (AccumReg 7), amhh3 = lanes 4-7
        let bmh3 = ctx.accumulator.read(7);
        let lane =
            |n: &str, k: usize| (pattern_word(n, 2 * k) as u64) | ((pattern_word(n, 2 * k + 1) as u64) << 32);
        assert_eq!(bmh3[0], lane("amhl3", 0));
        assert_eq!(bmh3[3], lane("amhl3", 3));
        assert_eq!(bmh3[4], lane("amhh3", 0));
        assert_eq!(
            ctx.mask.read(2),
            [word("q2"), pattern_word("q2", 1), pattern_word("q2", 2), pattern_word("q2", 3)]
        );
    }

    #[test]
    fn the_checked_in_artifact_is_current() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tools/harness/scrub_kernel.json");
        let have: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(&path).unwrap_or_default())
                .unwrap_or(serde_json::Value::Null);
        assert!(
            have == artifact_json(),
            "{} is stale: regenerate with `cargo run --bin scrub-kernel > tools/harness/scrub_kernel.json`",
            path.display()
        );
    }
}
